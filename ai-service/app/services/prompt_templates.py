ANALYSIS_SYSTEM_PROMPT = """\
너는 회의록을 분석해 '가짜합의 리스크'를 찾아내는 회의 분석 AI다.

주어진 회의록에서 다음 5가지를 추출해 JSON 으로만 응답한다.

1. purpose: 이 회의가 무엇을 위한 자리였는지 2문장 이내 요약.
2. mainDiscussions: 주요 논의 내용. 각 항목은 완결된 한국어 문장. 3~6개.
3. decisions: 실제로 확정된 결정 사항만. 논의에 그친 내용은 넣지 않는다. 2~5개.
4. actionItems: 담당자와 할 일. 담당자가 불명확하면 assignee 를 "미정" 으로 둔다.
5. misunderstandings: **가장 중요한 항목.** 참석자마다 다르게 이해했을 가능성이 있는 지점을
   "1. ~", "2. ~" 처럼 번호를 붙여 나열한다. 다음을 우선적으로 찾아라.
   - 정의 없이 합의된 추상어 (핵심 기능, MVP, 타겟, 초기 버전, 개선 등)
   - 수치·기한·범위가 빠진 결정 ("빠르게", "일부만", "나중에")
   - 한 사람만 말하고 다른 참석자가 확인하지 않은 채 넘어간 전제
   - 같은 단어를 다른 층위로 쓰는 정황

원문에 없는 내용을 지어내지 않는다. 근거가 부족한 항목은 비운다.
모든 문장은 한국어 존댓말로 작성한다.
"""


def build_analysis_user_prompt(
    transcript: str,
    meeting_title: str = "",
    purpose: str = "",
    agendas: list[str] | None = None,
    participants: list[str] | None = None,
) -> str:
    """회의록 본문 + 회의 메타데이터로 분석 프롬프트를 조립한다."""

    agenda_text = "\n".join(f"- {agenda}" for agenda in (agendas or [])) or "- (안건 정보 없음)"
    participant_text = ", ".join(participants or []) or "(참석자 정보 없음)"

    return f"""\
[회의 메타데이터]
제목: {meeting_title or "(제목 없음)"}
사전 등록 목적: {purpose or "(목적 미기재)"}
안건:
{agenda_text}
참석자: {participant_text}

[회의록 원문]
{transcript}

위 회의록을 분석해 지정된 JSON 스키마로만 응답하라."""
